import { describe, expect, test } from "bun:test";
import {
  baseTitle,
  catnoKey,
  extractCatnos,
  extractDiscogsLinks,
  parseAutoDescription,
  parseVideoTitle,
  similarity,
  splitArtists,
} from "../src/text.ts";
import { parseLink } from "../src/links.ts";

describe("parseVideoTitle", () => {
  // Real titles from the test set / YouTube search results.
  const cases: [string, Partial<ReturnType<typeof parseVideoTitle>>][] = [
    ["Rhythim Is Rhythim - Strings Of Life (Transmat | 1987)", { artist: "Rhythim Is Rhythim", title: "Strings Of Life", label: "Transmat", year: 1987 }],
    ["P.R.D. – I Want To... (Vocal) Rare Italo Disco 1984", { artist: "P.R.D.", title: "I Want To...", mix: "Vocal", extra: "Rare Italo Disco 1984" }],
    ["Floating Points - 'Ablaze' (Official Audio)", { artist: "Floating Points", title: "Ablaze", mix: undefined, label: undefined }],
    ["Kerri Chandler - Four (Raw Grooves EP)", { artist: "Kerri Chandler", title: "Four", album: "Raw Grooves EP" }],
    ["PREMIERE: Chaos In The CBD - Midnight In Peckham [In Dust We Trust]", { artist: "Chaos In The CBD", title: "Midnight In Peckham", label: "In Dust We Trust" }],
    ["Strada - It's The Monkey! (12'' Version) 1984", { artist: "Strada", title: "It's The Monkey!", mix: "12'' Version" }],
    ['Ego Neco – You + I ? (1984 - 12" - Italo Disco)', { artist: "Ego Neco", title: "You + I ?", year: 1984, label: undefined }],
    ["Savage - Only You (1984) (Maxi Single) (Vinyl, 12'') (Italo-Disco, Euro-Disco)", { artist: "Savage", title: "Only You", year: 1984, label: undefined, album: undefined }],
    ["A1. Unknown Artist - Untitled [WHITE001]", { artist: "Unknown Artist", title: "Untitled", catnoHints: ["WHITE001"] }],
    ["Moodymann - I Can't Kick This Feeling When It Hits [KDJ 26]", { artist: "Moodymann", catnoHints: ["KDJ 26"] }],
    ["Some Song Without Separator", { artist: undefined, title: "Some Song Without Separator" }],
  ];
  for (const [raw, want] of cases) {
    test(raw, () => {
      const got = parseVideoTitle(raw);
      for (const [k, v] of Object.entries(want)) expect((got as any)[k]).toEqual(v);
    });
  }
});

describe("similarity", () => {
  test("punctuation/case/abbreviation tolerant", () => {
    expect(similarity("Mr. Fingers", "Mr Fingers")).toBe(1);
    expect(similarity("P.R.D.", "PRD")).toBe(1);
    expect(similarity("Rhythim Is Rhythim", "Rhythim Is Rhythim (2)")).toBe(1);
    expect(similarity("Beyoncé", "Beyonce")).toBe(1);
  });
  test("partial overlaps are damped", () => {
    expect(similarity("Four", "Four Tet")).toBeLessThan(0.85);
    expect(similarity("Strings Of Life", "Strings")).toBeLessThan(0.85);
    expect(similarity("Can You Feel It", "Strings Of Life")).toBeLessThan(0.4);
  });
});

test("baseTitle strips mix decorations", () => {
  expect(baseTitle("Can You Feel It (Vocal)")).toBe("Can You Feel It");
  expect(baseTitle("Track 1 - Remaster")).toBe("Track 1");
  expect(baseTitle("Strings Of Life (Juice Bar Mix)")).toBe("Strings Of Life");
});

test("splitArtists", () => {
  expect(splitArtists("Fred again.., Skrillex & Four Tet")).toEqual(["Fred again..", "Skrillex", "Four Tet"]);
  expect(splitArtists("Chaos In The CBD feat. Someone")).toEqual(["Chaos In The CBD", "Someone"]);
});

test("catnos", () => {
  expect(extractCatnos("Label: Tanga Label – TL 004\nCat#: TL 004\nFormat: Vinyl\nMP3 320")).toEqual(["TL 004"]);
  expect(catnoKey("TX-117")).toBe(catnoKey("tx 0117"));
  expect(catnoKey("MS-1")).toBe(catnoKey("MS 001"));
});

test("discogs links in descriptions", () => {
  const d = `Buy: https://www.discogs.com/release/12345-Artist-Title
  old style: http://www.discogs.com/Rhythim-Is-Rhythim-Strings-Of-Life/master/4521
  localised: https://www.discogs.com/de/release/999 and again https://discogs.com/release/12345`;
  expect(extractDiscogsLinks(d)).toEqual([
    { type: "release", id: 12345 },
    { type: "master", id: 4521 },
    { type: "release", id: 999 },
  ]);
});

test("YouTube auto-generated description", () => {
  const d = `Provided to YouTube by Transmat

Strings of Life · Rhythim Is Rhythim

Strings of Life

℗ 1987 Transmat

Released on: 1987-01-01

Auto-generated by YouTube.`;
  expect(parseAutoDescription(d)).toEqual({ label: "Transmat", title: "Strings of Life", artists: ["Rhythim Is Rhythim"], album: "Strings of Life", year: 1987 });
  expect(parseAutoDescription("just some text")).toBeUndefined();
});

describe("parseLink", () => {
  test("spotify", () => {
    expect(parseLink("https://open.spotify.com/track/2jwRKUOBoN1hiMFuuKdIJE")).toEqual({ platform: "spotify", kind: "track", id: "2jwRKUOBoN1hiMFuuKdIJE" });
    expect(parseLink("https://open.spotify.com/intl-es/track/7JCbvWYwm3ukA6r9Gmh6H8?si=abc").id).toBe("7JCbvWYwm3ukA6r9Gmh6H8");
    expect(parseLink("spotify:album:abc123").kind).toBe("album");
  });
  test("apple", () => {
    expect(parseLink("https://music.apple.com/gb/song/track-1-remaster/1803420574")).toEqual({ platform: "apple", kind: "track", id: "1803420574", country: "gb" });
    expect(parseLink("https://music.apple.com/us/album/crush/1475361065?i=1475361070")).toEqual({ platform: "apple", kind: "track", id: "1475361070", albumId: "1475361065", country: "us" });
    expect(parseLink("https://music.apple.com/gb/album/computer-games-ep/338666715")).toEqual({ platform: "apple", kind: "album", id: "338666715", country: "gb" });
  });
  test("youtube", () => {
    expect(parseLink("https://www.youtube.com/watch?v=5oMUQKLzXH4&pp=0gcJCdgAo7VqN5tD")).toEqual({ platform: "youtube", kind: "video", id: "5oMUQKLzXH4" });
    expect(parseLink("https://youtu.be/8e5aWNpU_b8?t=10").id).toBe("8e5aWNpU_b8");
    expect(parseLink("https://music.youtube.com/watch?v=abc&list=x").id).toBe("abc");
    expect(parseLink("https://m.youtube.com/shorts/xyz").id).toBe("xyz");
  });
});
